export function makeT(lang: Lang) {
  const i = IDX[lang];
  return (key: string, fallback?: string, vars?: Record<string, string | number>): string => {
    let s = D[key] ? D[key][i] || D[key][0] : (fallback ?? key);
    if (vars) for (const k in vars) s = s.replace('{' + k + '}', String(vars[k]));
    return s;
  };
}

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: ReturnType<typeof makeT> }>({
  lang: 'en', setLang: () => {}, t: makeT('en')
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>('en');
  useEffect(() => {
    let timer: ReturnType<typeof setTimeout> | undefined;
    try {
      const v = localStorage.getItem('tycoon_lang') as Lang | null;
      if (v === 'en' || v === 'vi' || v === 'zh') timer = setTimeout(() => setLang(v), 0);
    } catch { /* ignore */ }
    return () => { if (timer) clearTimeout(timer); };
  }, []);
  const set = (l: Lang) => {
    setLang(l);
    try { localStorage.setItem('tycoon_lang', l); } catch { /* ignore */ }
  };
  return <Ctx.Provider value={{ lang, setLang: set, t: makeT(lang) }}>{children}</Ctx.Provider>;
}

export const useT = () => useContext(Ctx);
